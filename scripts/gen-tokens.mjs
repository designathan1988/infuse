#!/usr/bin/env node
// gen-tokens — compiles the DTCG .tokens.json sources into the one consumed artifact:
//   ui/css/tokens.css (custom properties per theme, inside @layer tokens).
// JavaScript reads the same values from the cascade (getComputedStyle), so there is no second copy.
// Run: node scripts/gen-tokens.mjs   (no dependencies; output is committed so `go build` never needs node)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = p => join(root, 'ui', 'tokens', p);
const read = f => JSON.parse(readFileSync(dir(f), 'utf8'));

const primitives = read('primitives.tokens.json');
const sizes = read('size.tokens.json');
const light = read('color.light.tokens.json');
const dark = read('color.dark.tokens.json');

// ---- resolve {a.b.c} references against a merged context (a token graph per theme)
function flatten(node, path, out, ctx) {
  for (const [k, v] of Object.entries(node || {})) {
    if (k.startsWith('$')) continue;
    const p = path ? `${path}.${k}` : k;
    if (v && typeof v === 'object' && v.$value === undefined) flatten(v, p, out, ctx);
    else out[p] = resolve(String(v.$value), ctx);
  }
  return out;
}
function resolve(value, ctx) {
  // resolves every {a.b.c} occurrence, including references embedded in composite values (shadows)
  for (let pass = 0; pass < 10 && /\{[^}]+\}/.test(value); pass++) {
    value = value.replace(/\{([^}]+)\}/g, (m, key) => {
      if (ctx[key] === undefined) throw new Error(`unknown token reference: {${key}}`);
      return ctx[key];
    });
  }
  if (/\{[^}]+\}/.test(value)) throw new Error(`token reference cycle: ${value}`);
  return value;
}
function graph(files) {
  const ctx = {};
  for (const f of files) flatten(f, '', ctx, ctx);
  return ctx;
}
const toVar = path => '--' + path.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/\./g, '-').toLowerCase();

const sizeG = graph([primitives, sizes]);
const lightG = graph([primitives, sizes, light]);
const darkG = graph([primitives, sizes, dark]);

// Paths a file itself declares (references excluded) — what differs per theme.
function ownPaths(node, path = '', out = new Set()) {
  for (const [k, v] of Object.entries(node || {})) {
    if (k.startsWith('$')) continue;
    const p = path ? `${path}.${k}` : k;
    if (v && typeof v === 'object' && v.$value === undefined) ownPaths(v, p, out);
    else out.add(p);
  }
  return out;
}
const themeable = ownPaths(light);
const cssVar = (g, filter) => Object.entries(g)
  .filter(([k]) => filter(k))
  .map(([k, v]) => `  ${toVar(k)}: ${v};`).join('\n');

// Theme: :root carries sizes + light; [data-theme=dark] overrides the themeable set only.
const css = `/* GENERATED by scripts/gen-tokens.mjs from ui/tokens/*.tokens.json (W3C DTCG format).
   Do not edit by hand — edit the token sources and regenerate. Layer order is declared here. */
@layer reset, tokens, base, layout, components, utilities;

@layer tokens {
  :root {
    color-scheme: light;
${cssVar(lightG, k => !themeable.has(k))}
${cssVar(lightG, k => themeable.has(k))}
  }
  :root[data-theme="dark"] {
    color-scheme: dark;
${cssVar(darkG, k => themeable.has(k))}
  }
}
`;
mkdirSync(join(root, 'ui', 'css'), { recursive: true });
writeFileSync(join(root, 'ui', 'css', 'tokens.css'), css);

console.log(`gen-tokens: ${Object.keys(lightG).length} light / ${Object.keys(darkG).length} dark tokens -> ui/css/tokens.css`);
